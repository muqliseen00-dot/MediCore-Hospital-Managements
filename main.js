/* Small progressive enhancements; all core workflows work without JavaScript. */
document.addEventListener('DOMContentLoaded', () => {
  // Animate statistic counters when they enter the viewport.
  const counters = document.querySelectorAll('[data-count]');
  const counterObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      const node = entry.target;
      const target = Number(node.dataset.count || 0);
      const start = performance.now();
      const duration = 850;
      const tick = now => {
        const progress = Math.min((now - start) / duration, 1);
        node.textContent = Math.round(target * (1 - Math.pow(1 - progress, 3))).toLocaleString('en-IN');
        if (progress < 1) requestAnimationFrame(tick);
      };
      requestAnimationFrame(tick);
      observer.unobserve(node);
    });
  }, { threshold: 0.3 });
  counters.forEach(counter => counterObserver.observe(counter));

  // Reveal cards as the user scrolls down the page.
  const revealObserver = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll('.panel, .section-heading, .stat-card').forEach(item => revealObserver.observe(item));

  // Dashboard chart: chart data is generated by Flask from SQLite aggregates.
  if (window.mediCoreCharts && window.Chart) {
    const canvas = document.getElementById('weeklyChart');
    if (canvas) new Chart(canvas, {
      type: 'bar',
      data: { labels: window.mediCoreCharts.labels, datasets: [{ label: 'Appointments', data: window.mediCoreCharts.values, backgroundColor: '#1E5BFF', borderRadius: 8, maxBarThickness: 34 }] },
      options: { plugins: { legend: { display: false } }, scales: { x: { grid: { display: false } }, y: { beginAtZero: true, ticks: { precision: 0 }, grid: { color: '#f0e8df' } } }, responsive: true }
    });
    const departmentCanvas = document.getElementById('departmentChart');
    if (departmentCanvas) new Chart(departmentCanvas, {
      type: 'doughnut',
      data: { labels: window.mediCoreCharts.deptLabels, datasets: [{ data: window.mediCoreCharts.deptValues, backgroundColor: ['#0B2A6F','#1E5BFF','#FF7A1A','#FFB067','#5A3A22'], borderWidth: 0 }] },
      options: { plugins: { legend: { position: 'bottom', labels: { boxWidth: 9, font: { family: 'Poppins', size: 9 } } } }, responsive: true }
    });
  }

  // Custom cursor is disabled for touch devices by CSS.
  const cursor = document.querySelector('.cursor-dot');
  if (cursor && window.matchMedia('(pointer:fine)').matches) {
    document.addEventListener('mousemove', event => {
      cursor.style.left = `${event.clientX}px`;
      cursor.style.top = `${event.clientY}px`;
    });
    document.querySelectorAll('a,button').forEach(element => {
      element.addEventListener('mouseenter', () => cursor.classList.add('hover'));
      element.addEventListener('mouseleave', () => cursor.classList.remove('hover'));
    });
  }
});
